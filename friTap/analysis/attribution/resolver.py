"""Offline destination attribution: map a captured host to its owning entity.

:class:`TrackerResolver` answers "who owns this host, what kind of service is
it, and is it first- or third-party" using two offline datasets:

* ``data/trackers.json`` — a friTap-curated ``domain -> {owner, category}``
  seed shipped with the package (no Tracker Radar data; see
  ``data/README.md``).
* ``data/public_suffix_list.dat`` — a snapshot of the Mozilla Public Suffix
  List, used to compute the registrable domain (eTLD+1).

An optional local ``data/trackers_full.json`` — the full DuckDuckGo Tracker
Radar distillation (CC BY-NC-SA 4.0), generated by
``dev/update_tracker_radar.py`` and never published — is preferred over the
seed when present (see :func:`default_trackers_path`).

The resolver performs **no network and no I/O at import time**. The data
files are read once, lazily, when a :class:`TrackerResolver` is constructed.

Trust model: the owner and category strings come from the bundled list and are
therefore *trusted* — they are safe to surface directly and must **not** be
wrapped in an ``untrusted`` envelope. Only the captured host itself is
untrusted input; callers are responsible for escaping/capping it before
display. This module never echoes attacker-controlled bytes back verbatim: the
host is normalised (lowercased, label-split) and only its registrable domain,
computed from the trusted PSL, is returned.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional

_DATA_DIR = Path(__file__).resolve().parent / "data"
DEFAULT_TRACKERS_PATH = _DATA_DIR / "trackers.json"
#: Local-only full Tracker Radar map (CC BY-NC-SA 4.0); never shipped.
FULL_TRACKERS_PATH = _DATA_DIR / "trackers_full.json"
DEFAULT_PSL_PATH = _DATA_DIR / "public_suffix_list.dat"


def default_trackers_path() -> Path:
    """Return the tracker map to load when none is given explicitly.

    Prefers the local-only full map (:data:`FULL_TRACKERS_PATH`) when it
    exists, else the shipped seed (:data:`DEFAULT_TRACKERS_PATH`). The module
    globals are read at call time so tests can monkeypatch them.
    """
    if FULL_TRACKERS_PATH.is_file():
        return FULL_TRACKERS_PATH
    return DEFAULT_TRACKERS_PATH

#: Party classification values.
PARTY_FIRST = "first"
PARTY_THIRD = "third"
PARTY_UNKNOWN = "unknown"


@dataclass(frozen=True)
class Attribution:
    """Result of classifying a single host.

    :param registrable_domain: the eTLD+1 of the host (``None`` when the host
        is itself a public suffix or otherwise has no registrable domain).
    :param owner: the owning entity's display name, or ``None`` if unknown.
    :param category: the tracker category slug (e.g. ``advertising``,
        ``analytics``, ``social``, ``cdn``), or ``None`` if unknown.
    :param party: ``first``, ``third`` or ``unknown`` (see :class:`PARTY_*`).
    """

    registrable_domain: Optional[str]
    owner: Optional[str]
    category: Optional[str]
    party: str

    def as_dict(self) -> Dict[str, Optional[str]]:
        """Return a plain ``dict`` view (stable key order) for serialisation."""
        return {
            "registrable_domain": self.registrable_domain,
            "owner": self.owner,
            "category": self.category,
            "party": self.party,
        }


def _normalize_host(host: str) -> str:
    """Lowercase, strip surrounding whitespace and any trailing dot."""
    return host.strip().rstrip(".").lower()


def _split_labels(host: str) -> List[str]:
    """Split a normalised host into DNS labels, dropping empty ones."""
    return [label for label in host.split(".") if label]


class _PublicSuffixList:
    """Minimal Public Suffix List matcher implementing the eTLD+1 algorithm.

    Supports exact rules, ``*`` wildcard rules and ``!`` exception rules, per
    https://publicsuffix.org/list/ . Comment and blank lines are ignored.
    """

    def __init__(self, exact: set, wildcards: set, exceptions: set) -> None:
        self._exact = exact
        self._wildcards = wildcards
        self._exceptions = exceptions

    @classmethod
    def from_file(cls, path: Path) -> "_PublicSuffixList":
        exact: set = set()
        wildcards: set = set()
        exceptions: set = set()
        with open(path, "r", encoding="utf-8") as handle:
            for raw in handle:
                line = raw.strip()
                if not line or line.startswith("//"):
                    continue
                rule = line.lower()
                if rule.startswith("!"):
                    exceptions.add(tuple(_split_labels(rule[1:])))
                elif rule.startswith("*."):
                    wildcards.add(tuple(_split_labels(rule[2:])))
                else:
                    exact.add(tuple(_split_labels(rule)))
        return cls(exact, wildcards, exceptions)

    def _public_suffix_labels(self, labels: List[str]) -> List[str]:
        """Return the public-suffix labels for an already-normalised host."""
        count = len(labels)
        # Exception rules take priority: the public suffix is the matched rule
        # minus its leftmost label.
        for i in range(count):
            suffix = tuple(labels[i:])
            if suffix in self._exceptions:
                return list(suffix[1:])

        best: Optional[List[str]] = None
        # Longest matching exact rule wins.
        for i in range(count):
            suffix = tuple(labels[i:])
            if suffix in self._exact and (best is None or len(suffix) > len(best)):
                best = list(suffix)
        # Wildcard rule ``*.base`` matches one arbitrary label followed by base.
        for i in range(count):
            base = tuple(labels[i + 1:])
            if base in self._wildcards:
                match = labels[i:]
                if best is None or len(match) > len(best):
                    best = list(match)

        if best is None:
            # Default rule "*": the rightmost single label is the public suffix.
            return labels[-1:]
        return best

    def registrable_domain(self, host: str) -> Optional[str]:
        """Return the eTLD+1 of ``host``, or ``None`` if it has none."""
        labels = _split_labels(_normalize_host(host))
        if not labels:
            return None
        suffix_len = len(self._public_suffix_labels(labels))
        if len(labels) <= suffix_len:
            # The host is itself a public suffix (e.g. ``co.uk``): no eTLD+1.
            return None
        return ".".join(labels[-(suffix_len + 1):])


class TrackerResolver:
    """Resolve hosts to ``{registrable_domain, owner, category, party}``.

    The datasets are loaded once on construction and reused across calls; no
    network or implicit I/O happens afterwards. When ``trackers_path`` is
    ``None`` the map comes from :func:`default_trackers_path`.
    """

    def __init__(
        self,
        trackers_path: Path | str | None = None,
        psl_path: Path | str = DEFAULT_PSL_PATH,
    ) -> None:
        if trackers_path is None:
            trackers_path = default_trackers_path()
        self._trackers = self._load_trackers(Path(trackers_path))
        self._psl = _PublicSuffixList.from_file(Path(psl_path))

    @staticmethod
    def _load_trackers(path: Path) -> Dict[str, Dict[str, Optional[str]]]:
        """Load the distilled tracker map (``domain -> {owner, category}``)."""
        with open(path, "r", encoding="utf-8") as handle:
            payload = json.load(handle)
        entries = payload.get("entries", {}) if isinstance(payload, dict) else {}
        normalized: Dict[str, Dict[str, Optional[str]]] = {}
        for domain, meta in entries.items():
            if not isinstance(meta, dict):
                continue
            normalized[_normalize_host(domain)] = {
                "owner": meta.get("owner"),
                "category": meta.get("category"),
            }
        return normalized

    def _lookup(self, host: str, registrable: Optional[str]) -> Optional[Dict[str, Optional[str]]]:
        """Find the most specific tracker entry for ``host``.

        Walks from the full host inward (so ``graph.facebook.com`` is matched
        before ``facebook.com``), stopping at the registrable domain.
        """
        if registrable is None:
            return None
        labels = _split_labels(host)
        reg_len = registrable.count(".") + 1
        for i in range(0, len(labels) - reg_len + 1):
            candidate = ".".join(labels[i:])
            entry = self._trackers.get(candidate)
            if entry is not None:
                return entry
        return None

    def _first_party_domains(self, first_party_domains: Iterable[str]) -> set:
        """Normalise caller-supplied first-party names to registrable domains."""
        result: set = set()
        for raw in first_party_domains:
            registrable = self._psl.registrable_domain(raw)
            result.add(registrable if registrable else _normalize_host(raw))
        return result

    def classify(self, host: str, first_party_domains: Iterable[str] = ()) -> Attribution:
        """Classify a single host into an :class:`Attribution`.

        :param host: the captured host (untrusted; normalised internally).
        :param first_party_domains: domains considered first-party for this
            capture; each is reduced to its registrable domain before matching.
        """
        normalized = _normalize_host(host)
        registrable = self._psl.registrable_domain(normalized)
        entry = self._lookup(normalized, registrable)
        owner = entry["owner"] if entry else None
        category = entry["category"] if entry else None

        first_party = self._first_party_domains(first_party_domains)
        if registrable is not None and registrable in first_party:
            party = PARTY_FIRST
        elif owner is not None or category is not None:
            party = PARTY_THIRD
        else:
            party = PARTY_UNKNOWN

        return Attribution(
            registrable_domain=registrable,
            owner=owner,
            category=category,
            party=party,
        )
